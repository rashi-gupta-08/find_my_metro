// Public read-only checks against the local app. Account and report mutations
// below are intercepted in the browser; no passenger account is created.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
async function main() {
  const root='http://localhost:5173';
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const output=path.resolve('.local/journey-checks');
  await fs.mkdir(output,{recursive:true});
  const errors=[],checks=[];
  try {
    const context=await browser.newContext({viewport:{width:1440,height:1000}});
    const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
    const frames=[];
    page.on('websocket',socket=>{if(socket.url().includes('/ws/journeys?'))socket.on('framereceived',frame=>{try{frames.push(JSON.parse(frame.payload));}catch{}});});
    await page.goto(root);await page.getByRole('button',{name:'Find my route',exact:true}).waitFor();
    const network=await (await page.request.get(root+'/api/v1/network')).json();
    assert.equal(network.simulated,false);assert(network.stations.length>=265);checks.push('265 real station catalogue; generated inputs disabled');
    assert.equal(await page.getByRole('button',{name:'Run journey',exact:true}).count(),0);
    assert.equal(await page.getByLabel('Metro operator').count(),0);
    await page.getByRole('button',{name:'Find my route',exact:true}).click();
    await page.locator('.journey-card').first().waitFor();
    assert(await page.locator('.journey-card').count()>1);
    assert((await page.locator('.journey-card').first().innerText()).includes('separate ticket'));
    assert((await page.locator('.journey-card').first().innerText()).includes('Aqua Line'));checks.push('Cross-operator routes include walking, re-entry and full station details');
    await page.locator('.route-method').filter({hasText:'Journey updates connected'}).waitFor();
    await page.waitForFunction(()=>document.querySelectorAll('.journey-source').length>=3);
    assert((await page.locator('.journey-live').first().innerText()).includes('No identified upcoming train yet'));
    assert.equal(await page.locator('.journey-source[data-source="wsn"]').count(),0);
    for(let attempt=0;attempt<15 && frames.length<2;attempt++)await page.waitForTimeout(250);
    assert(frames.length>=2);assert(frames.every(frame=>frame.type==='journey_snapshot' && frame.snapshot_version));
    checks.push('WebSocket journey snapshots expose source/context/freshness without invented live trains');
    const previousVersion=frames.at(-1).snapshot_version;
    await context.setOffline(true);
    await page.locator('.route-method').filter({hasText:'Saved journey'}).waitFor();
    assert((await page.locator('.journey-live').first().innerText()).includes('Saved status'));
    await context.setOffline(false);
    await page.locator('.route-method').filter({hasText:'Journey updates connected'}).waitFor();
    for(let attempt=0;attempt<15 && !frames.some(frame=>frame.snapshot_version>previousVersion);attempt++)await page.waitForTimeout(250);
    assert(frames.some(frame=>frame.snapshot_version>previousVersion));
    checks.push('Offline journey is labelled saved; reconnect receives a newer complete snapshot');
    await page.getByRole('button',{name:'Less walking',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Less walking',exact:true}).getAttribute('aria-pressed'),'true');
    for(let attempt=0;attempt<30 && !frames.some(frame=>frame.preference==='least_walking');attempt++)await page.waitForTimeout(250);
    assert(frames.some(frame=>frame.preference==='least_walking'));
    await page.locator('.journey-card').first().waitFor();
    await page.locator('.route-method').filter({hasText:'Journey updates connected'}).waitFor();
    await page.screenshot({path:path.join(output,'journey-desktop.png'),fullPage:false});
    await page.locator('.journey-live').first().screenshot({path:path.join(output,'backend-journey-status.png')});
    await page.getByRole('button',{name:'From station',exact:true}).click();
    await page.getByRole('combobox',{name:'Search from station'}).fill('Kashmere');
    await page.getByRole('option',{name:/Kashmere Gate/}).click();
    await page.getByRole('button',{name:'To station',exact:true}).click();
    await page.getByRole('combobox',{name:'Search to station'}).fill('Noida Sector - 137');
    // Names are retained from NMRC's official station list.
    if (await page.getByRole('option').count()===0) await page.getByRole('combobox',{name:'Search to station'}).fill('137');
    await page.getByRole('option',{name:/137/}).click();
    await page.getByRole('button',{name:'Find my route',exact:true}).click();
    await page.locator('.journey-card').first().waitFor();checks.push('Searchable origin/destination across Delhi and Noida');
    await page.getByRole('button',{name:'Report',exact:true}).click();await page.getByRole('dialog').waitFor();
    assert((await page.getByRole('dialog').innerText()).includes('Welcome back'));
    await page.keyboard.press('Escape');checks.push('Anonymous reports require a passenger session');
    await page.getByLabel('Network scope').selectOption('aqua');
    await context.setOffline(true);
    await page.getByRole('button',{name:'Find my route',exact:true}).click();
    await page.locator('.journey-card').first().waitFor();
    await page.locator('.route-method').filter({hasText:'Offline Aqua Line estimate'}).waitFor();
    assert.equal(await page.locator('.journey-card').count(),1);
    assert((await page.locator('.journey-card').first().innerText()).includes('21 stations'));
    checks.push('All 21 Aqua stations can form a new offline journey without a previously cached route');
    await context.setOffline(false);
    await page.locator('.route-method').filter({hasText:'Journey updates connected'}).waitFor();
    await context.close();
    const phone=await browser.newContext({viewport:{width:390,height:844},permissions:['geolocation'],geolocation:{latitude:28.58685,longitude:77.37275,accuracy:10}});
    await phone.route('**/api/v1/auth/me',route=>route.fulfill({json:{user:{id:'isolated-browser-check',username:'check',display_name:'Check passenger',role:'passenger',verified_contributor:false},csrf_token:'browser-check-token'}}));
    await phone.route('**/api/v1/reports/mine',route=>route.fulfill({json:{reports:[],generated_at:new Date().toISOString()}}));
    await phone.route('**/api/v1/contributions/mine',route=>route.fulfill({json:{points:0,validated_contributions:0,badges:[],award_policy:'Isolated UI check'}}));
    let submitted;
    await phone.route('**/api/v1/reports/batch',async route=>{
      submitted=route.request().postDataJSON();
      await route.fulfill({status:202,json:{acknowledgements:submitted.reports.map((r,i)=>({event_id:r.event_id,client_event_id:r.event_id,status:'queued',index:i}))}});
    });
    const mobile=await phone.newPage();mobile.on('pageerror',e=>errors.push(e.message));
    await mobile.goto(root);await mobile.getByRole('button',{name:'Find my route',exact:true}).waitFor();
    await mobile.getByRole('button',{name:'Find my route',exact:true}).click();await mobile.locator('.journey-card').first().waitFor();
    assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await mobile.screenshot({path:path.join(output,'journey-phone.png'),fullPage:false});checks.push('390-pixel mobile layout has no horizontal overflow');
    await mobile.getByRole('button',{name:'Report',exact:true}).click();
    await mobile.getByRole('heading',{name:'Report a station update'}).waitFor();
    await mobile.getByRole('button',{name:'Report at station'}).click();
    await mobile.getByRole('combobox',{name:'Search report at station'}).fill('52');
    await mobile.getByRole('option',{name:/52/}).click();
    await mobile.getByRole('button',{name:'Check GPS and send report'}).click();
    await mobile.getByRole('status').filter({hasText:'Report saved'}).waitFor();
    assert.equal(submitted.reports[0].station_id,'dmrc-sftn');assert.equal(submitted.reports[0].delay_seconds,300);assert.equal(submitted.reports[0].accuracy_m,10);
    assert(!submitted.reports[0].trip_id);checks.push('Surface report captures GPS, observation time and delay without inventing train identity');
    await mobile.screenshot({path:path.join(output,'surface-report-phone.png'),fullPage:false});
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(output,'results.json'),JSON.stringify({checks,errors,created_at:new Date().toISOString()},null,2));
    console.log(JSON.stringify({checks,errors,output},null,2));
  } finally { await browser.close(); }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
