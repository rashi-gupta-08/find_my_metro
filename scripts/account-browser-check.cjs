// Authentication mutations are intercepted: no passenger accounts or passwords change.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');

async function main(){
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const output=path.resolve('.local/account-checks');await fs.mkdir(output,{recursive:true});
  const checks=[],errors=[];
  try{
    const context=await browser.newContext({viewport:{width:1050,height:850}});
    let loginStatus=401,submittedReset=0,resetBody;
    await context.route('**/api/v1/auth/me',r=>r.fulfill({json:{user:null,csrf_token:null}}));
    await context.route('**/api/v1/auth/login',r=>r.fulfill({status:loginStatus,headers:{'Retry-After':'2'},json:{detail:loginStatus===429?'Too many requests. Try again shortly.':'Incorrect username or password'}}));
    await context.route('**/api/v1/auth/register',r=>r.fulfill({status:409,json:{detail:'This username is unavailable'}}));
    await context.route('**/api/v1/auth/password/reset',r=>{submittedReset++;resetBody=r.request().postDataJSON();return r.fulfill({json:{ok:true}});});
    const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://localhost:5173/');await page.getByRole('button',{name:'Sign in',exact:true}).click();
    const dialog=page.getByRole('dialog');
    await dialog.getByLabel('USERNAME',{exact:true}).fill(' rashi_gupta ');
    assert.equal(await dialog.getByLabel('USERNAME',{exact:true}).inputValue(),'rashi_gupta');
    await dialog.getByLabel('PASSWORD',{exact:true}).fill('isolated-test-password');
    await dialog.getByRole('button',{name:'Show password',exact:true}).click();
    assert.equal(await dialog.getByLabel('PASSWORD',{exact:true}).getAttribute('type'),'text');
    await dialog.getByRole('button',{name:'Hide password',exact:true}).click();
    await dialog.getByRole('button',{name:'Sign in',exact:true}).click();
    await dialog.getByRole('alert').filter({hasText:'Incorrect username or password'}).waitFor();
    assert(await dialog.getByRole('button',{name:'Forgot password?'}).isVisible());
    await page.screenshot({path:path.join(output,'sign-in-desktop.png')});
    checks.push('Wrong credentials remain rejected; username whitespace, visibility toggle and inline recovery action work');
    await dialog.getByRole('button',{name:'Create an account',exact:true}).click();
    await dialog.getByLabel('YOUR NAME',{exact:true}).fill('Isolated check');
    await dialog.getByLabel('PASSWORD',{exact:true}).fill('isolated-register-password');
    await dialog.getByRole('button',{name:'Create account',exact:true}).click();
    await dialog.getByRole('heading',{name:'Welcome back'}).waitFor();
    await dialog.getByRole('alert').filter({hasText:'already registered'}).waitFor();
    assert.equal(await dialog.getByLabel('USERNAME',{exact:true}).inputValue(),'rashi_gupta');
    assert.equal(await dialog.getByLabel('PASSWORD',{exact:true}).inputValue(),'');
    checks.push('Duplicate registration returns to sign-in, retains username and clears password');
    loginStatus=429;
    await dialog.getByLabel('PASSWORD',{exact:true}).fill('isolated-test-password');
    await dialog.getByRole('button',{name:'Sign in',exact:true}).click();
    const retry=dialog.getByRole('button',{name:/Try again in/});await retry.waitFor();assert(await retry.isDisabled());
    await dialog.getByRole('button',{name:'Sign in',exact:true}).waitFor({timeout:5000});
    checks.push('Rate-limit response disables submit until the server retry interval ends');
    const fakeToken='isolated-browser-recovery-token-1234567890';
    const sent=[];page.on('request',r=>sent.push(r.url()));
    await page.goto('http://localhost:5173/#reset-password='+fakeToken+'&username=rashi_gupta');
    await dialog.getByRole('heading',{name:'Reset your password'}).waitFor();
    assert.equal(new URL(page.url()).hash,'');
    assert.equal(await dialog.getByLabel('RECOVERY CODE',{exact:true}).inputValue(),fakeToken);
    assert(!sent.some(url=>url.includes(fakeToken)));
    assert(!await page.evaluate(token=>JSON.stringify({...localStorage}).includes(token),fakeToken));
    await dialog.getByLabel('NEW PASSWORD',{exact:true}).fill('new-isolated-password');
    await dialog.getByLabel('CONFIRM NEW PASSWORD',{exact:true}).fill('mismatched-isolated-password');
    await dialog.getByRole('button',{name:'Reset password',exact:true}).click();
    await dialog.getByRole('alert').filter({hasText:'do not match'}).waitFor();assert.equal(submittedReset,0);
    await dialog.getByLabel('CONFIRM NEW PASSWORD',{exact:true}).fill('new-isolated-password');
    await dialog.getByRole('button',{name:'Reset password',exact:true}).click();
    await dialog.getByRole('status').filter({hasText:'password has been reset'}).waitFor();
    assert.equal(submittedReset,1);assert.equal(resetBody.token,fakeToken);
    assert.equal(await dialog.getByLabel('PASSWORD',{exact:true}).inputValue(),'');
    checks.push('Recovery fragment is removed and not stored; matching passwords submit the code in the body and return to sign-in');
    await page.setViewportSize({width:390,height:498});
    await dialog.getByRole('button',{name:'Forgot password?'}).click();
    const close=await dialog.getByRole('button',{name:'Close account'}).boundingBox();
    assert(close&&close.y>=0&&close.y+close.height<=498);
    const bounds=await dialog.boundingBox();assert(bounds&&bounds.x>=0&&bounds.x+bounds.width<=390);
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=390));
    await dialog.locator('.account-body').evaluate(e=>e.scrollTop=e.scrollHeight);
    assert(await dialog.getByRole('button',{name:'Close account'}).isVisible());
    await page.screenshot({path:path.join(output,'recovery-phone.png')});
    await page.keyboard.press('Escape');assert.equal(await page.getByRole('dialog').count(),0);
    assert.notEqual(await page.evaluate(()=>document.body.style.overflow),'hidden');
    checks.push('Small-screen form scrolls within the dialog; header/close stay visible and Escape restores the page');
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(output,'results.json'),JSON.stringify({checks,errors},null,2));
    console.log(JSON.stringify({checks,errors},null,2));
  }finally{await browser.close();}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
