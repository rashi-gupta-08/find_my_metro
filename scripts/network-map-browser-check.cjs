// Read-only UI verification. No accounts, reports or passenger records are created.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const output='.local/network-map-checks';
(async()=>{
  await fs.mkdir(output,{recursive:true});
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const errors=[],checks=[];
  try {
    const context=await browser.newContext({viewport:{width:1500,height:1100}});
    const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
    await page.goto('http://localhost:5173/');
    await page.getByRole('button',{name:'Map',exact:true}).click();
    await page.getByRole('heading',{name:'Metro map',exact:true}).waitFor();
    const network=await (await page.request.get('http://localhost:5173/api/v1/network')).json();
    const diagram=page.locator('.explorer-map > svg');
    assert.equal(await page.locator('.explorer-station').count(),network.stations.length);
    assert.equal(await page.getByRole('heading',{name:/Next trains/}).count(),0);
    assert((await diagram.boundingBox()).y<430);
    assert(await page.locator('.explorer-station-labels text').count()<network.stations.length);
    checks.push('Map is the primary view; every catalogue station remains present with readable uncluttered labels');
    const original=await diagram.getAttribute('viewBox');
    await page.getByRole('button',{name:'Zoom in',exact:true}).click();
    await page.getByLabel('Map zoom',{exact:true}).filter({hasText:'140%'}).waitFor();
    assert(Number((await diagram.getAttribute('viewBox')).split(' ')[2])<Number(original.split(' ')[2]));
    const selectedBefore=await page.locator('.explorer-station[aria-pressed="true"]').getAttribute('aria-label');
    const bounds=await diagram.boundingBox();
    await page.mouse.move(bounds.x+90,bounds.y+100);await page.mouse.down();
    await page.mouse.move(bounds.x+160,bounds.y+135,{steps:8});await page.mouse.up();
    assert.notEqual(await diagram.getAttribute('viewBox'),original);
    assert.equal(await page.locator('.explorer-station[aria-pressed="true"]').getAttribute('aria-label'),selectedBefore);
    await page.getByRole('button',{name:'Fit network to view',exact:true}).click();
    await page.getByLabel('Map zoom',{exact:true}).filter({hasText:'100%'}).waitFor();
    await diagram.focus();await page.keyboard.press('+');
    await page.getByLabel('Map zoom',{exact:true}).filter({hasText:'135%'}).waitFor();
    await page.keyboard.press('0');
    checks.push('Button and keyboard zoom, drag panning without accidental station selection, and fit-to-view controls work');
    const filter=page.getByRole('group',{name:'Map line filter',exact:true});
    await filter.getByRole('button',{name:'Blue Line',exact:true}).click();
    const blue=new Set(network.lines.filter(l=>(l.family_id??l.id)==='dmrc-ln3').flatMap(l=>l.station_ids));
    assert.equal(await page.locator('.explorer-station').count(),blue.size);
    assert.equal(await page.locator('.explorer-tracks polyline').count(),2);
    checks.push('Line filters keep both Blue branches and show exactly their configured stations');
    await page.getByRole('button',{name:'Find a station',exact:true}).click();
    await page.getByRole('combobox',{name:'Search map stations'}).fill('Rajiv Chowk');
    await page.getByRole('combobox',{name:'Search map stations'}).press('Enter');
    await page.getByRole('heading',{name:'Rajiv Chowk',exact:true}).waitFor();
    await page.getByLabel('Map zoom',{exact:true}).filter({hasText:'240%'}).waitFor();
    assert((await page.locator('.explorer-station-detail').innerText()).includes('Change between 2 lines'));
    assert((await page.locator('.explorer-station-detail').innerText()).includes('Underground'));
    checks.push('Station search centres the map and shows correct serving lines, context and interchange details');
    await page.getByRole('button',{name:'Find a station',exact:true}).click();
    await page.getByRole('combobox',{name:'Search map stations'}).fill('Pari Chowk');
    await page.getByRole('option',{name:/Pari Chowk/}).click();
    await page.getByRole('heading',{name:'Pari Chowk',exact:true}).waitFor();
    await page.getByLabel('Map zoom',{exact:true}).filter({hasText:'240%'}).waitFor();
    assert.equal(await page.locator('.explorer-station').count(),network.stations.length);
    checks.push('Searching outside a filtered line restores the network and centres the selected station');
    await page.getByRole('group',{name:'Map network filter'}).getByRole('button',{name:'Noida Metro',exact:true}).click();
    assert.equal(await page.locator('.explorer-station').count(),21);
    assert.equal(await page.locator('.explorer-tracks polyline').count(),1);
    await page.getByRole('checkbox',{name:'Station names'}).check();
    await page.screenshot({path:output+'/map-aqua-desktop.png',fullPage:true});
    await page.getByRole('button',{name:'Select Depot Station station',exact:true}).click();
    await page.getByRole('heading',{name:'Depot Station',exact:true}).waitFor();
    await page.getByRole('button',{name:'Start here',exact:true}).click();
    await page.getByRole('button',{name:'From station',exact:true}).filter({hasText:'Depot Station'}).waitFor();
    checks.push('Noida filter shows all 21 Aqua stations; clicking a station and Start here updates the journey planner');
    await page.getByRole('button',{name:'Map',exact:true}).click();
    await page.getByRole('button',{name:'Find a station',exact:true}).click();
    await page.getByRole('combobox',{name:'Search map stations'}).fill('Rajiv');
    await page.getByRole('option',{name:/Rajiv Chowk/}).click();
    await page.getByRole('button',{name:'Go here',exact:true}).click();
    await page.getByRole('button',{name:'To station',exact:true}).filter({hasText:'Rajiv Chowk'}).waitFor();
    checks.push('Go here sets the destination without fabricating a route or live arrival');
    await page.getByRole('button',{name:'Map',exact:true}).click();
    await page.getByRole('button',{name:'Reset map filters and view'}).click();
    await page.screenshot({path:output+'/map-desktop.png',fullPage:true});
    assert.equal(await page.getByRole('heading',{name:'Arrival times aren’t available yet'}).count(),0);
    assert((await page.locator('.explorer-arrivals').innerText()).includes('Arrival times aren’t available yet'));
    const phone=await browser.newContext({viewport:{width:390,height:844}});
    const mobile=await phone.newPage();mobile.on('pageerror',e=>errors.push(e.message));
    await mobile.goto('http://localhost:5173/');await mobile.getByRole('button',{name:'Map',exact:true}).click();
    await mobile.getByRole('heading',{name:'Metro map',exact:true}).waitFor();
    assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await mobile.getByRole('group',{name:'Map network filter'}).getByRole('button',{name:'Noida Metro',exact:true}).click();
    await mobile.screenshot({path:output+'/map-phone.png',fullPage:true});
    await mobile.getByRole('button',{name:'Find a station',exact:true}).click();
    await mobile.getByRole('combobox',{name:'Search map stations'}).fill('137');
    await mobile.getByRole('option',{name:/137/}).click();
    assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await phone.setOffline(true);
    await mobile.getByRole('button',{name:'Zoom in',exact:true}).click();
    assert.equal(await mobile.locator('.explorer-station').count(),21);
    checks.push('390px mobile layout and station search have no overflow; filtering and zoom remain usable offline');
    assert.deepEqual(errors,[]);
    await fs.writeFile(output+'/results.json',JSON.stringify({checks,errors,created_at:new Date().toISOString()},null,2));
    console.log(JSON.stringify({checks,errors},null,2));
  }catch(error){console.error(error);throw error;}
  finally{await browser.close();}
})().catch(()=>{process.exitCode=1;});
