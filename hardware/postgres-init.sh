#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 --set=owner_password="$OWNER_PASSWORD" --set=app_password="$APP_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE metro_owner LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION', :'owner_password') \gexec
SELECT format('CREATE ROLE metro LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION', :'app_password') \gexec
ALTER DATABASE metro OWNER TO metro_owner;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE metro TO metro;
GRANT USAGE ON SCHEMA public TO metro;
ALTER DEFAULT PRIVILEGES FOR ROLE metro_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO metro;
ALTER DEFAULT PRIVILEGES FOR ROLE metro_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO metro;
SQL
